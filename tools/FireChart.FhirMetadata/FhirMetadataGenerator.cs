using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace FireChart.Tools.FhirMetadata;

// A core release whose metadata goes into FireChart.Viewer.Core (Fhir/Metadata/{ClassName}.g.cs); Folder names it in a project (search-forms/{Folder})
public sealed record CoreRelease(string Release, string Folder, string ClassName, string PackageName, string PackageVersion);

// The C# of FhirReleaseMetadata of a release (FireChart.Viewer.Core), from the JSON files of its core package: the resource types, the bindings
// of the elements of the resources and datatypes (the snapshots of the specializations) and the search parameters, one per type of their base, with
// what a search form needs of each (its type, expression, the hint of that type, the plain path and the types of its element). Ordered and written the
// same way every time: a new run on the same package gives the same text
public static partial class FhirMetadataGenerator
{
    public static IReadOnlyList<CoreRelease> Releases { get; } =
    [
        new("STU3", "r3", "Stu3Metadata", "hl7.fhir.r3.core", "3.0.2"),
        new("R4", "r4", "R4Metadata", "hl7.fhir.r4.core", "4.0.1"),
        new("R4B", "r4b", "R4BMetadata", "hl7.fhir.r4b.core", "4.3.0"),
        new("R5", "r5", "R5Metadata", "hl7.fhir.r5.core", "5.0.0")
    ];

    public const string Tool = "public/tools/FireChart.FhirMetadata";

    // The resource types of a package that a search form is made for: the concrete resources (no abstract one, no profile)
    public static IReadOnlyList<string> ResourceTypes(string packageFolder)
    {
        var resources = Resources(packageFolder);
        try
        {
            return ResourceTypes(resources);
        }
        finally
        {
            resources.ForEach(document => document.Dispose());
        }
    }

    public static string Generate(string packageFolder, CoreRelease release)
    {
        ArgumentNullException.ThrowIfNull(release);
        var resources = Resources(packageFolder);
        try
        {
            return Generate(resources, release);
        }
        finally
        {
            resources.ForEach(document => document.Dispose());
        }
    }

    private static string Generate(List<JsonDocument> resources, CoreRelease release)
    {
        var elements = Elements(resources);
        var types = ResourceTypes(resources);
        var parameters = Parameters(resources, elements);

        var text = new StringBuilder();
        text.Append("// <auto-generated>\n")
            .Append(CultureInfo.InvariantCulture, $"// The metadata of {release.Release}, generated from {release.PackageName}@{release.PackageVersion}: do not edit.\n")
            .Append("// </auto-generated>\n")
            .Append("#nullable enable\n\n")
            .Append("using FireChart.Viewer.Core.Forms;\n\n")
            .Append("namespace FireChart.Viewer.Core.Fhir.Metadata;\n\n")
            .Append(CultureInfo.InvariantCulture, $"internal static class {release.ClassName}\n{{\n")
            .Append("    public static FhirReleaseMetadata Create()\n    {\n")
            .Append(CultureInfo.InvariantCulture,
                    $"        return new FhirReleaseMetadata({Literal(release.Release)}, {Literal(release.PackageName)}, {Literal(release.PackageVersion)}, ResourceTypes(), Bindings(), Parameters());\n")
            .Append("    }\n");
        AppendRows(text, "string", "ResourceTypes", [.. types.Select(Literal)]);
        AppendRows(text, "ElementBinding", "Bindings",
                   [.. elements.Values.Where(e => e.Binding is not null)
                               .OrderBy(e => e.Path, StringComparer.Ordinal)
                               .Select(e => $"new({Literal(e.Path)}, {Literal(e.Binding!.Url)}, {Optional(e.Binding.Version)}, BindingStrength.{e.Binding.Strength})")]);
        AppendRows(text, "SearchParameterMetadata", "Parameters",
                   [.. parameters.Select(p => $"new({Literal(p.Type)}, {Literal(p.Code)}, SearchParameterType.{p.ParameterType}, {Optional(p.Url)}, {Optional(p.Expression)}, {List(p.Bases)}, {Optional(p.Hint)}, {Optional(p.Path)}, {List(p.ElementTypes)}, {List(p.Comparators)}, {List(p.Modifiers)}, {Flag(p.MultipleOr)}, {Flag(p.MultipleAnd)}, {List(p.Chains)}, {List(p.Targets)})")]);
        text.Append("}\n");
        return text.ToString();
    }

    // The interpreter of .NET in the browser refuses a method with too many locals ("locals size too big", a Debug build): the rows go into methods of
    // RowsPerMethod each, joined by the method of the name
    private const int RowsPerMethod = 100;

    private static void AppendRows(StringBuilder text, string type, string name, IReadOnlyList<string> rows)
    {
        var parts = rows.Chunk(RowsPerMethod).ToList();
        text.Append(CultureInfo.InvariantCulture, $"\n    private static {type}[] {name}()\n    {{\n        return [")
            .AppendJoin(", ", parts.Select((_, i) => $".. {name}{i}()"))
            .Append("];\n    }\n");
        for (var i = 0; i < parts.Count; i++)
        {
            text.Append(CultureInfo.InvariantCulture, $"\n    private static {type}[] {name}{i}()\n    {{\n        return\n        [\n");
            foreach (var row in parts[i])
            {
                text.Append(CultureInfo.InvariantCulture, $"            {row},\n");
            }

            text.Append("        ];\n    }\n");
        }
    }

    // The JSON resources of a package folder (package/*.json), in the order of their file names; package.json and the index are not resources
    private static List<JsonDocument> Resources(string packageFolder)
    {
        return [.. Directory.EnumerateFiles(packageFolder, "*.json")
                            .Where(file => Path.GetFileName(file) is not ("package.json" or ".index.json"))
                            .Order(StringComparer.Ordinal)
                            .Select(file => JsonDocument.Parse(File.ReadAllText(file)))
                            .Where(document => document.RootElement.ValueKind == JsonValueKind.Object)];
    }

    private static IEnumerable<JsonElement> OfType(IEnumerable<JsonDocument> resources, string resourceType)
    {
        return resources.Select(document => document.RootElement).Where(root => Text(root, "resourceType") == resourceType);
    }

    private static List<string> ResourceTypes(List<JsonDocument> resources)
    {
        return [.. OfType(resources, "StructureDefinition")
                   .Where(sd => Text(sd, "kind") == "resource" && Text(sd, "derivation") == "specialization" && Bool(sd, "abstract") != true)
                   .Select(sd => Text(sd, "type") ?? Text(sd, "id"))
                   .OfType<string>()
                   .Distinct(StringComparer.Ordinal)
                   .Order(StringComparer.Ordinal)];
    }

    // The elements of the snapshots of the resources and the datatypes (specializations: no profiles) by path: their types and their binding. STU3
    // names the value set by valueSetReference or valueSetUri, the later releases by valueSet; a version is after "|"
    private static Dictionary<string, ElementRow> Elements(List<JsonDocument> resources)
    {
        var rows = new Dictionary<string, ElementRow>(StringComparer.Ordinal);
        var structures = OfType(resources, "StructureDefinition")
            .Where(sd => Text(sd, "derivation") == "specialization" && Text(sd, "kind") is "resource" or "complex-type");
        foreach (var sd in structures)
        {
            if (!sd.TryGetProperty("snapshot", out var snapshot) || !snapshot.TryGetProperty("element", out var elements) || elements.ValueKind != JsonValueKind.Array)
            {
                continue;
            }

            foreach (var element in elements.EnumerateArray())
            {
                if (Text(element, "path") is not { } path || rows.ContainsKey(path))
                {
                    continue;
                }

                var types = element.TryGetProperty("type", out var typeList) && typeList.ValueKind == JsonValueKind.Array
                    ? typeList.EnumerateArray().Select(t => Text(t, "code")).Where(c => !string.IsNullOrEmpty(c)).OfType<string>()
                              .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList()
                    : [];
                rows[path] = new ElementRow(path, types, BindingOf(element));
            }
        }

        return rows;
    }

    private static BindingRow? BindingOf(JsonElement element)
    {
        if (!element.TryGetProperty("binding", out var binding))
        {
            return null;
        }

        var reference = Text(binding, "valueSet") ?? Text(binding, "valueSetUri")
                        ?? (binding.TryGetProperty("valueSetReference", out var r) ? Text(r, "reference") : null);
        if (reference is null || Strength(Text(binding, "strength")) is not { } strength)
        {
            return null;
        }

        var bar = reference.IndexOf('|', StringComparison.Ordinal);
        return new BindingRow(bar < 0 ? reference : reference[..bar], bar < 0 ? null : reference[(bar + 1)..], strength);
    }

    private static List<ParameterRow> Parameters(List<JsonDocument> resources, Dictionary<string, ElementRow> elements)
    {
        var rows = new Dictionary<string, ParameterRow>(StringComparer.Ordinal);
        foreach (var root in OfType(resources, "SearchParameter").OrderBy(p => Text(p, "url"), StringComparer.Ordinal))
        {
            if (Text(root, "code") is not { } code || ParameterType(Text(root, "type")) is not { } parameterType)
            {
                continue;
            }

            var bases = Strings(root, "base");
            var expression = Text(root, "expression");
            foreach (var type in bases)
            {
                var path = PathOf(expression, type);
                var element = path is null ? null : elements.GetValueOrDefault(path);
                rows.TryAdd(type + "." + code, new ParameterRow(type, code, parameterType, Text(root, "url"), expression, bases, ExtractHint(Text(root, "description"), type),
                                                                path, element?.Types ?? [], Strings(root, "comparator"), Strings(root, "modifier"),
                                                                Bool(root, "multipleOr"), Bool(root, "multipleAnd"), Strings(root, "chain"), Strings(root, "target")));
            }
        }

        return [.. rows.Values.OrderBy(row => row.Type, StringComparer.Ordinal).ThenBy(row => row.Code, StringComparer.Ordinal)];
    }

    // The one plain path ("Patient.gender") of the expression for the type; null when there is none or several, or functions and choices
    private static string? PathOf(string? expression, string type)
    {
        if (string.IsNullOrWhiteSpace(expression))
        {
            return null;
        }

        var paths = expression.Split('|', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries)
                              .Where(path => path.StartsWith(type + ".", StringComparison.Ordinal) && PlainPath().IsMatch(path))
                              .ToList();
        return paths.Count == 1 ? paths[0] : null;
    }

    // The description of a parameter shared by several resources lists them as "* [Patient](patient.html): text": the line of the type. Otherwise
    // the first sentence without markdown
    internal static string? ExtractHint(string? description, string type)
    {
        if (string.IsNullOrWhiteSpace(description))
        {
            return null;
        }

        if (description.TrimStart().StartsWith("Multiple Resources", StringComparison.OrdinalIgnoreCase))
        {
            foreach (var line in description.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries))
            {
                var match = ResourceLine().Match(line);
                if (match.Success && match.Groups["type"].Value == type)
                {
                    return StripMarkdown(match.Groups["text"].Value).Trim();
                }
            }

            return null;
        }

        var plain = StripMarkdown(description).Trim();
        var end = SentenceEnd().Match(plain);
        var sentence = end.Success ? plain[..end.Index] : plain;
        return string.IsNullOrWhiteSpace(sentence) ? null : sentence.Trim();
    }

    private static string StripMarkdown(string text)
    {
        return MarkdownLink().Replace(text, "${text}").Replace("*", string.Empty, StringComparison.Ordinal);
    }

    private static string? ParameterType(string? text)
    {
        return text switch
        {
            "string" => "String",
            "token" => "Token",
            "date" => "Date",
            "number" => "Number",
            "quantity" => "Quantity",
            "reference" => "Reference",
            "uri" => "Uri",
            "composite" => "Composite",
            "special" => "Special",
            _ => null
        };
    }

    private static string? Strength(string? text)
    {
        return text switch
        {
            "required" => "Required",
            "extensible" => "Extensible",
            "preferred" => "Preferred",
            "example" => "Example",
            _ => null
        };
    }

    private static string? Text(JsonElement element, string name)
    {
        return element.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() : null;
    }

    private static bool? Bool(JsonElement element, string name)
    {
        return element.TryGetProperty(name, out var value) && value.ValueKind is JsonValueKind.True or JsonValueKind.False ? value.GetBoolean() : null;
    }

    // A string or an array of strings (base is a string in STU3), sorted
    private static List<string> Strings(JsonElement element, string name)
    {
        if (!element.TryGetProperty(name, out var value))
        {
            return [];
        }

        IEnumerable<string?> items = value.ValueKind switch
        {
            JsonValueKind.String => [value.GetString()],
            JsonValueKind.Array => value.EnumerateArray().Where(item => item.ValueKind == JsonValueKind.String).Select(item => item.GetString()),
            _ => []
        };
        return [.. items.OfType<string>().Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)];
    }

    private static string List(IReadOnlyList<string> items)
    {
        return items.Count == 0 ? "[]" : "[" + string.Join(", ", items.Select(Literal)) + "]";
    }

    private static string Optional(string? text)
    {
        return text is null ? "null" : Literal(text);
    }

    private static string Flag(bool? value)
    {
        return value switch
        {
            true => "true",
            false => "false",
            _ => "null"
        };
    }

    private static string Literal(string text)
    {
        var literal = new StringBuilder("\"");
        foreach (var c in text)
        {
            literal.Append(c switch
            {
                '"' => "\\\"",
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ when char.IsControl(c) => "\\u" + ((int)c).ToString("x4", CultureInfo.InvariantCulture),
                _ => c.ToString()
            });
        }

        return literal.Append('"').ToString();
    }

    [GeneratedRegex(@"^\s*\*\s*\[(?<type>[A-Za-z]+)\]\([^)]*\)\s*:\s*(?<text>.+)$")]
    private static partial Regex ResourceLine();

    // A full stop followed by a blank or the end, but not one that closes an abbreviation ("e.g.", "i.e.", "etc.") or sits in a number ("4.0.1"),
    // and a line break
    [GeneratedRegex(@"(?<!\b[A-Za-z])(?<!\betc)\.(?=\s|$)|[\r\n]")]
    private static partial Regex SentenceEnd();

    [GeneratedRegex(@"\[(?<text>[^\]]*)\]\([^)]*\)")]
    private static partial Regex MarkdownLink();

    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9]*(\.[A-Za-z][A-Za-z0-9]*)+$")]
    private static partial Regex PlainPath();

    private sealed record BindingRow(string Url, string? Version, string Strength);

    private sealed record ElementRow(string Path, List<string> Types, BindingRow? Binding);

    private sealed record ParameterRow(string Type, string Code, string ParameterType, string? Url, string? Expression, List<string> Bases, string? Hint, string? Path,
                                       List<string> ElementTypes, List<string> Comparators, List<string> Modifiers, bool? MultipleOr, bool? MultipleAnd,
                                       List<string> Chains, List<string> Targets);
}
